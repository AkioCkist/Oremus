import { Router } from 'express';
import * as controller from '../controllers/api.controller.js';
import * as story from '../controllers/story.controller.js';
import { requireAuth } from '../middleware/auth.js';
import { rateLimit } from '../middleware/rate-limit.js';
import { enforcePostMediaSize, postUpload, upload } from '../middleware/upload.js';
import { compressUploadedImages } from '../media/image.js';
import { asyncHandler } from '../utils/async-handler.js';

export const apiRoutes = Router();
apiRoutes.use(requireAuth);
apiRoutes.patch('/profile', upload.fields([{ name: 'avatar', maxCount: 1 }, { name: 'cover', maxCount: 1 }]), compressUploadedImages, asyncHandler(controller.updateProfile));
apiRoutes.get('/profile/photos', asyncHandler(controller.photoLibrary));
apiRoutes.delete('/profile/photos', asyncHandler(controller.deletePhoto));
apiRoutes.patch('/profile/details', asyncHandler(controller.updateDetails));
apiRoutes.post('/profile/photo', rateLimit('profile-photo', 30, 3600), upload.single('photo'), compressUploadedImages, asyncHandler(controller.updatePhoto));
apiRoutes.post('/users/:userId/follow', asyncHandler(controller.toggleFollow));
apiRoutes.post('/users/:userId/friendship', asyncHandler(controller.changeFriendship));
apiRoutes.get('/users/:userId/break', asyncHandler(controller.breakState));
apiRoutes.post('/users/:userId/break', asyncHandler(controller.takeBreak));
apiRoutes.post('/users/:userId/block', asyncHandler(controller.blockUser));
apiRoutes.post('/posts', rateLimit('post', 20, 3600), postUpload.array('images'), enforcePostMediaSize, compressUploadedImages, asyncHandler(controller.createPost));
apiRoutes.get('/posts/:postId', asyncHandler(controller.postDetail));
apiRoutes.patch('/posts/:postId', postUpload.array('images'), enforcePostMediaSize, compressUploadedImages, asyncHandler(controller.updatePost));
apiRoutes.put('/posts/:postId/media/:mediaId', postUpload.single('photo'), enforcePostMediaSize, compressUploadedImages, asyncHandler(controller.replacePostMedia));
apiRoutes.delete('/posts/:postId/media/:mediaId', asyncHandler(controller.removePostMedia));
apiRoutes.delete('/posts/:postId', asyncHandler(controller.deletePost));
apiRoutes.post('/posts/:postId/reactions', asyncHandler(controller.react));
apiRoutes.post('/posts/:postId/comments', rateLimit('comment', 60, 3600), asyncHandler(controller.comment));
apiRoutes.post('/groups', rateLimit('group', 5, 3600), upload.single('cover'), compressUploadedImages, asyncHandler(controller.createGroup));
apiRoutes.patch('/groups/:groupId', upload.single('cover'), compressUploadedImages, asyncHandler(controller.updateGroup));
apiRoutes.post('/groups/:groupId/leave', asyncHandler(controller.leaveGroup));
apiRoutes.post('/groups/:groupId/invites', rateLimit('group-invite', 60, 3600), asyncHandler(controller.inviteToGroup));
apiRoutes.post('/group-posts/:postId/decision', asyncHandler(controller.decideGroupPost));
apiRoutes.post('/groups/:groupId/join', asyncHandler(controller.requestJoin));
apiRoutes.post('/group-requests/:requestId/decision', asyncHandler(controller.decideJoin));
apiRoutes.post('/conversations', asyncHandler(controller.createConversation));
apiRoutes.post('/conversations/:conversationId/messages', rateLimit('message', 120, 60), asyncHandler(controller.sendMessage));
apiRoutes.get('/stories', asyncHandler(story.tray));
apiRoutes.post('/stories', rateLimit('story', 30, 3600), upload.single('media'), compressUploadedImages, asyncHandler(story.create));
apiRoutes.patch('/stories/settings', asyncHandler(story.settings));
apiRoutes.post('/stories/:storyId/view', asyncHandler(story.view));
apiRoutes.post('/stories/:storyId/reactions', asyncHandler(story.react));
apiRoutes.post('/stories/:storyId/replies', rateLimit('message', 120, 60), asyncHandler(story.reply));
apiRoutes.get('/stories/:storyId/viewers', asyncHandler(story.viewers));
apiRoutes.delete('/stories/:storyId', asyncHandler(story.remove));
apiRoutes.get('/places', rateLimit('places', 60, 60), asyncHandler(controller.places));
apiRoutes.get('/places/nearby', rateLimit('places', 60, 60), asyncHandler(controller.placesNearby));
apiRoutes.get('/notifications', asyncHandler(controller.notifications));
apiRoutes.post('/notifications/read', asyncHandler(controller.readNotifications));
apiRoutes.get('/search', asyncHandler(controller.search));
apiRoutes.get('/dev/cache', asyncHandler(controller.diagnostics));

